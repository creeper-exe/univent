/* ═══════════════════════════════════════════════════════════════════════
   UNIVENT — hero headline: "WE ENGINEER / AIR."

   Concept: air pressure acting on typography. "AIR." is rasterised from the
   real DOM text into a texture, then drawn through a fragment shader that
   warps it — a stretch/translate field for the entrance, a pointer-driven
   pressure field afterwards, and underneath both a continuous flow field
   (advected fbm noise) that keeps the word breathing at rest. The smear is
   derived from the word's actual *speed*, so the blur is a consequence of
   movement rather than a keyframed effect.

   Gellix is a static family (no fvar), so variable-font width axes are not
   available — hence the shader route, scoped to this one word.

   Layering, in order of graceful degradation:
     no JS / no GSAP  → plain DOM headline, nothing hidden
     reduced motion   → plain DOM headline, no canvas, no interaction
     coarse pointer   → GSAP transform entrance on the DOM text, no canvas
     no WebGL         → same as coarse pointer
     desktop + WebGL  → full shader entrance + airflow cursor field

   The DOM <h1> always holds the real text and always occupies the layout;
   the canvas is an overlay. Nothing here can shift the page.
   ═══════════════════════════════════════════════════════════════════════ */

(function () {
  "use strict";

  var root = document.documentElement;
  var hero = document.getElementById("hero");
  if (!hero) return;

  var airEl  = hero.querySelector("[data-hero-air]");        /* inline span, "AIR." */
  var lineEl = hero.querySelector("[data-hero-air-line]");   /* its block line box  */
  var weEl   = hero.querySelector("[data-hero-we]");
  var fades  = [].slice.call(hero.querySelectorAll("[data-hero-fade]"));

  /* Header chrome is generated by build-content.py into every page, so it
     carries no hero-specific markup. .hero-armed only ever lands on the home
     page, which makes it a safe hook to reach the shared header through. */
  var navEl     = document.getElementById("nav");
  var actionsEl = document.querySelector(".header-actions");

  var disarm = function () { root.classList.remove("hero-armed"); };

  if (!airEl || !lineEl || !weEl || !window.gsap) { disarm(); return; }

  var mqReduce = matchMedia("(prefers-reduced-motion: reduce)");
  var mqCoarse = matchMedia("(pointer: coarse)");

  if (mqReduce.matches) { disarm(); return; }

  var simple = mqCoarse.matches || innerWidth < 860;

  /* ───────────────────────── entrance timing ─────────────────────────
     WE ENGINEER settles, then AIR. is pushed in and stopped. Total ≈ 1.9s. */
  var T_WE     = 0.10;   /* WE ENGINEER begins                      */
  var T_AIR    = 0.46;   /* AIR. burst begins                     */
  var D_PUSH   = 0.60;   /* travel + deceleration into overshoot  */
  var D_SETTLE = 0.34;   /* controlled release of the overshoot   */
  var D_DRAW   = 0.60;   /* stretched flight — still wide on arrival */
  var D_SQUASH = 0.18;   /* the stop: stretch snaps into compression */
  var D_RELAX  = 0.44;   /* compression back to true proportions  */
  var T_COPY   = 1.18;   /* supporting copy, nav, CTA             */

  var STRETCH  = 2.2;    /* horizontal scale at launch */
  var ARRIVE   = 1.18;   /* still visibly stretched as it lands */
  var COMPRESS = 0.88;   /* momentary squash at the stop */

  /* ═══════════════════ shared: supporting copy reveal ═══════════════════ */

  /* Watchdog. index.html's failsafe drops .hero-armed, but that cannot undo
     the inline opacity:0 GSAP writes when it arms a fromTo — so if a timeline
     ever stalls (a pathologically long frame, a backgrounded tab resuming
     oddly), the copy would stay invisible. Jumping it to the end is always
     safe: the end state is simply "everything visible". */
  function guard(tl) {
    setTimeout(function () {
      if (tl.progress() < 1) tl.progress(1);
    }, 5000);
    return tl;
  }

  function addChrome(tl) {
    if (fades.length) {
      tl.fromTo(fades,
        { opacity: 0, y: 18 },
        { opacity: 1, y: 0, duration: 0.72, ease: "power2.out", stagger: 0.07 },
        T_COPY);
    }

    /* Below 900px .nav is the fixed mobile drawer — it is opacity:0 by design
       and an inline opacity from here would jam it open. Desktop only, and
       cleared afterwards so a resize into mobile leaves nothing behind. */
    if (!simple) {
      var chrome = [navEl, actionsEl].filter(Boolean);
      if (chrome.length) {
        tl.to(chrome, {
          opacity: 1, duration: 0.6, ease: "power2.out",
          onComplete: function () { gsap.set(chrome, { clearProps: "opacity" }); }
        }, T_COPY + 0.08);
      }
    }
  }

  /* ═══════════════════ path A — simplified (no shader) ═══════════════════
     Mobile, low-power and no-WebGL devices. Same choreography, expressed as
     a transform on the DOM text: momentum, overshoot, compression, settle —
     just without the smear. No cursor interaction. */

  function runSimple() {
    airEl.style.display = "inline-block";      /* transforms need a box */
    /* anchored on the leading edge, so the stretch trails behind the travel */
    airEl.style.transformOrigin = "right center";
    airEl.style.willChange = "transform, opacity";

    var tl = gsap.timeline({
      onComplete: function () {
        airEl.style.willChange = "";
        disarm();
      }
    });

    tl.fromTo(weEl, { opacity: 0, y: 30 },
      { opacity: 1, y: 0, duration: 0.80, ease: "power3.out" }, T_WE);

    tl.fromTo(airEl,
      { opacity: 0, x: "-38%", scaleX: STRETCH },
      { opacity: 1, duration: 0.16, ease: "none" }, T_AIR);

    tl.to(airEl, { x: "2%", duration: D_PUSH,   ease: "power3.out"   }, T_AIR)
      .to(airEl, { x: "0%", duration: D_SETTLE, ease: "power2.inOut" }, T_AIR + D_PUSH);

    tl.to(airEl, { scaleX: ARRIVE,   duration: D_DRAW,   ease: "power2.out" }, T_AIR)
      .to(airEl, { scaleX: COMPRESS, duration: D_SQUASH, ease: "power2.in"  }, T_AIR + D_DRAW)
      .to(airEl, { scaleX: 1,        duration: D_RELAX,  ease: "power2.out" }, T_AIR + D_DRAW + D_SQUASH);

    addChrome(tl);
    guard(tl);
  }

  /* ═══════════════════ path B — WebGL displacement ═══════════════════ */

  var VERT = [
    "attribute vec2 aPos;",
    "varying vec2 vUv;",
    "void main(){",
    "  vUv = vec2(aPos.x * 0.5 + 0.5, 0.5 - aPos.y * 0.5);",
    "  gl_Position = vec4(aPos, 0.0, 1.0);",
    "}"
  ].join("\n");

  var FRAG = [
    "precision mediump float;",
    "varying vec2 vUv;",
    "uniform sampler2D uTex;",
    "uniform vec2  uPointer;",   /* airflow source, screen uv          */
    "uniform vec2  uRadius;      // falloff radii, uv                  ",
    "uniform float uPull;        // pointer-driven wind strength       ",
    "uniform float uOffset;      // entrance translation, uv           ",
    "uniform float uScale;       // horizontal stretch                 ",
    "uniform float uPivot;       // stretch anchor, uv x               ",
    "uniform float uSmear;       // entrance trail length, uv          ",
    "uniform float uTime;        // seconds, drives the flow field       ",
    "uniform float uAlpha;",
    "uniform float uAspect;      // band width / height — keeps the field square",
    "uniform float uBreeze;      // 0..1 ambient airflow, up after the entrance",
    "",
    "#define TAPS 12",
    "",
    /* Smooth value noise. The earlier field hashed 32 hard horizontal bands
       and lerped between two integer time steps, so neighbouring scanlines
       jumped independently — that banding is what read as a glitch. This is
       continuous in x, y and t, so the word deforms the way air does. */
    "float hash21(vec2 p){",
    "  p = fract(p * vec2(123.34, 456.21));",
    "  p += dot(p, p + 45.32);",
    "  return fract(p.x * p.y);",
    "}",
    "float vnoise(vec2 p){",
    "  vec2 i = floor(p), f = fract(p);",
    "  vec2 u = f * f * (3.0 - 2.0 * f);",       /* smoothstep interpolation */
    "  float a = hash21(i);",
    "  float b = hash21(i + vec2(1.0, 0.0));",
    "  float c = hash21(i + vec2(0.0, 1.0));",
    "  float d = hash21(i + vec2(1.0, 1.0));",
    "  return mix(mix(a, b, u.x), mix(c, d, u.x), u.y);",
    "}",
    "float fbm(vec2 p){",
    "  return 0.60 * vnoise(p)",
    "       + 0.27 * vnoise(p * 2.07 + 11.7)",
    "       + 0.13 * vnoise(p * 4.13 + 31.3);",
    "}",
    "",
    /* Entrance transform (pivot/scale/offset) plus the flow displacement. */
    "vec4 sampleAt(vec2 uv, vec2 drift){",
    "  vec2 p = uv;",
    "  p.x = (p.x - uPivot) / uScale + uPivot;",
    "  p -= drift;",
    "  p.x -= uOffset;",
    "  if (p.x < 0.0 || p.x > 1.0 || p.y < 0.0 || p.y > 1.0) return vec4(0.0);",
    "  return texture2D(uTex, p);",
    "}",
    "",
    "void main(){",
    /* A wind lane, not a blob: long downstream, shallow across the flow. */
    "  vec2 d = (vUv - uPointer) / uRadius;",
    "  float w = exp(-dot(d, d));",
    "",
    /* The field is sampled in square units and drifts downstream, so its
       structure travels through the word rather than pulsing in place. */
    "  vec2 q = vec2(vUv.x, vUv.y / max(uAspect, 0.001)) * 2.6;",
    "  q.x -= uTime * 0.22;",
    "  q.y += uTime * 0.04;",
    "  vec2 flow = vec2(fbm(q), fbm(q + vec2(19.3, 7.1))) - 0.5;",
    "",
    /* Air is never steady. A slow, separate noise swells and lulls the whole
       field so the word breathes in gusts instead of drifting at one rate. */
    "  float gust = 0.70 + 0.60 * vnoise(vec2(uTime * 0.13, 3.3));",
    "",
    "  float wind = uPull * w;",
    /* ambient everywhere, stronger where the cursor is pushing */
    "  float amp  = uBreeze * 0.0052 * gust * (0.45 + 0.55 * w) + abs(wind) * 0.50;",
    "  vec2 drift = vec2(flow.x * amp * 2.4 + wind * 0.55,",
    "                    flow.y * amp * 1.1 * uAspect);",
    "",
    "  float s = uSmear + wind * (0.70 + 0.60 * abs(flow.x) * 2.0) * 0.80;",
    "",
    /* At rest this collapses to a single fetch. */
    "  if (abs(s) < 0.0004) {",
    "    gl_FragColor = sampleAt(vUv, drift) * uAlpha;",
    "    return;",
    "  }",
    /* Dither the taps per pixel, or a long trail resolves into countable
       ghosts instead of motion blur. The trail leans along the local flow,
       so a gust smears diagonally rather than in flat rows. */
    "  float j = fract(sin(dot(gl_FragCoord.xy, vec2(12.9898, 78.233))) * 43758.5453);",
    "  vec2 step = vec2(s, s * flow.y * 0.55 * uAspect);",
    "  vec4 sum = vec4(0.0);",
    "  for (int i = 0; i < TAPS; i++) {",
    /* taps reach backwards along the motion, so the trail trails */
    "    float f = (float(i) + j) / float(TAPS);",
    "    sum += sampleAt(vUv + f * step, drift);",
    "  }",
    "  gl_FragColor = sum / float(TAPS) * uAlpha;",
    "}"
  ].join("\n");

  var MAX_TEX = 4096;

  function compile(gl, type, src) {
    var s = gl.createShader(type);
    gl.shaderSource(s, src);
    gl.compileShader(s);
    if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) { gl.deleteShader(s); return null; }
    return s;
  }

  function runShader() {
    var canvas = document.createElement("canvas");
    canvas.className = "hero-air-canvas";
    canvas.setAttribute("aria-hidden", "true");

    var gl = canvas.getContext("webgl", {
      alpha: true, premultipliedAlpha: true, antialias: false,
      depth: false, stencil: false, powerPreference: "low-power"
    }) || canvas.getContext("experimental-webgl");

    if (!gl) return false;

    var vs = compile(gl, gl.VERTEX_SHADER, VERT);
    var fs = compile(gl, gl.FRAGMENT_SHADER, FRAG);
    if (!vs || !fs) return false;

    var prog = gl.createProgram();
    gl.attachShader(prog, vs);
    gl.attachShader(prog, fs);
    gl.linkProgram(prog);
    if (!gl.getProgramParameter(prog, gl.LINK_STATUS)) return false;
    gl.useProgram(prog);

    var buf = gl.createBuffer();
    gl.bindBuffer(gl.ARRAY_BUFFER, buf);
    gl.bufferData(gl.ARRAY_BUFFER,
      new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW);
    var aPos = gl.getAttribLocation(prog, "aPos");
    gl.enableVertexAttribArray(aPos);
    gl.vertexAttribPointer(aPos, 2, gl.FLOAT, false, 0, 0);

    var U = {};
    ["uTex", "uPointer", "uRadius", "uPull", "uOffset",
     "uScale", "uPivot", "uSmear", "uTime", "uAlpha",
     "uAspect", "uBreeze"].forEach(function (n) {
      U[n] = gl.getUniformLocation(prog, n);
    });

    var tex = gl.createTexture();
    gl.bindTexture(gl.TEXTURE_2D, tex);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.LINEAR);
    gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.LINEAR);
    gl.pixelStorei(gl.UNPACK_PREMULTIPLY_ALPHA_WEBGL, true);

    gl.enable(gl.BLEND);
    gl.blendFunc(gl.ONE, gl.ONE_MINUS_SRC_ALPHA);
    gl.uniform1i(U.uTex, 0);

    lineEl.appendChild(canvas);

    /* ─────────── geometry + rasterisation ───────────
       The band spans the full viewport so AIR. has somewhere off-screen to
       fly in from. Text is drawn at the exact position the DOM put it: an
       inline span's border box is the font's content box, so its top plus
       the ascent share of its height is the real baseline. */

    var band = { w: 0, h: 0, textX: 0, textW: 0 };

    function runs() {
      var out = [];
      [].forEach.call(airEl.childNodes, function (n) {
        if (n.nodeType === 3) {
          if (n.nodeValue) out.push({ text: n.nodeValue, color: getComputedStyle(airEl).color });
        } else if (n.nodeType === 1) {
          out.push({ text: n.textContent, color: getComputedStyle(n).color });
        }
      });
      return out;
    }

    function build() {
      var rect = airEl.getBoundingClientRect();
      var lRect = lineEl.getBoundingClientRect();
      if (!rect.width || !lRect.height) return false;

      var cs = getComputedStyle(airEl);
      var fontSize = parseFloat(cs.fontSize);
      var tracking = cs.letterSpacing === "normal" ? 0 : (parseFloat(cs.letterSpacing) || 0);

      var bw = root.clientWidth;                       /* excludes the scrollbar */
      var bh = Math.ceil(lRect.height * 1.7);

      var dpr = Math.min(window.devicePixelRatio || 1, 2);
      dpr = Math.min(dpr, MAX_TEX / bw, MAX_TEX / bh);

      var c = document.createElement("canvas");
      c.width  = Math.max(1, Math.round(bw * dpr));
      c.height = Math.max(1, Math.round(bh * dpr));

      var g = c.getContext("2d");
      g.scale(dpr, dpr);
      g.textBaseline = "alphabetic";
      g.font = cs.fontStyle + " " + cs.fontWeight + " " + fontSize + "px " + cs.fontFamily;
      if ("letterSpacing" in g) g.letterSpacing = tracking + "px";

      var m = g.measureText("H");
      var asc = m.fontBoundingBoxAscent, desc = m.fontBoundingBoxDescent;
      var ratio = (asc && desc) ? asc / (asc + desc) : 0.78;

      var bandTop = lRect.top + lRect.height / 2 - bh / 2;
      var baseline = (rect.top - bandTop) + rect.height * ratio;

      var x = rect.left;
      var startX = x;
      runs().forEach(function (r) {
        g.fillStyle = r.color;
        g.fillText(r.text, x, baseline);
        x += g.measureText(r.text).width;
      });

      band.w = bw;
      band.h = bh;
      band.textX = startX;
      band.textW = Math.max(1, x - startX);
      /* leading edge of the word: the stretch anchor during a left-to-right
         entry, so the letters draw out behind it rather than either side */
      band.pivot = x / bw;

      canvas.style.width  = bw + "px";
      canvas.style.height = bh + "px";
      /* The band is viewport-wide and its texture is drawn in viewport
         coordinates, so its left edge has to sit at viewport x=0. The CSS
         centring only did that while the headline spanned the full column
         width; pin it explicitly now that the hero is two columns. */
      canvas.style.left = (-lRect.left) + "px";
      canvas.style.transform = "translateY(-50%)";
      canvas.width  = c.width;
      canvas.height = c.height;

      gl.bindTexture(gl.TEXTURE_2D, tex);
      gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGBA, gl.RGBA, gl.UNSIGNED_BYTE, c);
      gl.viewport(0, 0, canvas.width, canvas.height);

      gl.uniform2f(U.uRadius, (fontSize * 2.0) / bw, (fontSize * 0.55) / bh);
      gl.uniform1f(U.uAspect, bw / bh);
      return true;
    }

    if (!build()) return false;

    airEl.style.opacity = "0";      /* still selectable, still read by AT */

    /* ─────────── live state ─────────── */

    var enter = { offset: 0, scale: 1, alpha: 0 };
    var pointer = { x: 0.5, y: 0.5 };
    var target  = { x: 0.5, y: 0.5 };
    var moved = 0, lastX = null, vel = 0, pull = 0;
    var smear = 0, prevShift = 0, clock = 0;
    var running = false, last = 0;
    var interactive = false, onScreen = true;
    /* ambient airflow, held at 0 through the entrance so the arrival reads
       as one clean move, then eased up to a permanent idle breeze */
    var breeze = 0, breezeTo = 0;

    var PULL_MAX  = 0.030;   /* uv — ceiling on how far the air can drag  */
    /* Tuned so a deliberate ~300px/s move barely registers, a brisk
       ~1000px/s move reads clearly, and only a flick reaches the ceiling. */
    var PULL_GAIN = 0.05;    /* uv of drag per uv/s of cursor speed       */
    /* Smear length per uv/s of travel. Deriving it from *speed* rather than
       from the raw per-frame delta is what keeps the trail steady: a long
       frame no longer produces a longer streak. */
    var TRAIL     = 0.050;
    var SMEAR_MAX = 0.070;

    function draw() {
      /* the anchor rides along with the word, so the stretch always trails
         the leading edge instead of being pinned to a spot on the screen */
      gl.uniform1f(U.uPivot,   band.pivot + enter.offset);
      gl.uniform1f(U.uOffset,  enter.offset);
      gl.uniform1f(U.uScale,   enter.scale);
      gl.uniform1f(U.uAlpha,   enter.alpha);
      gl.uniform1f(U.uPull,    pull);
      gl.uniform1f(U.uSmear,   smear);
      gl.uniform1f(U.uTime,    clock);
      gl.uniform1f(U.uBreeze,  breeze);
      gl.uniform2f(U.uPointer, pointer.x, pointer.y);
      gl.clearColor(0, 0, 0, 0);
      gl.clear(gl.COLOR_BUFFER_BIT);
      gl.drawArrays(gl.TRIANGLES, 0, 3);
    }

    /* Frame-rate independent smoothing toward a target. tau is the time
       constant in seconds — how long the value takes to cover ~63% of the
       remaining gap. Every lag in here is expressed that way so the feel is
       tunable in units that mean something. */
    function approach(cur, to, tau, dt) {
      return cur + (to - cur) * (1 - Math.exp(-dt / tau));
    }

    /* Air has almost no mass. Long time constants here are what made this
       read as a liquid: the word lagged, bulged, and oozed back. A gust
       arrives almost instantly and bleeds off only slightly slower, so the
       onset and the release are deliberately asymmetric. */
    var TAU_POS   = 0.05;   /* the field sits on the cursor, barely trailing */
    var TAU_VEL   = 0.07;   /* velocity estimate settles                     */
    var TAU_GUST  = 0.07;   /* pressure building — quick, but not a step     */
    var TAU_CALM  = 0.30;   /* pressure bleeding off once the cursor slows   */
    var TAU_SMEAR = 0.07;   /* trail tracks motion, minus the frame jitter   */

    function frame(now) {
      var dt = last ? Math.min((now - last) / 1000, 0.05) : 0.016;
      last = now;
      clock += dt;

      if (interactive) {
        pointer.x = approach(pointer.x, target.x, TAU_POS, dt);
        pointer.y = approach(pointer.y, target.y, TAU_POS, dt);

        var vRaw = moved / Math.max(dt, 0.001);
        moved = 0;
        vel = approach(vel, vRaw, TAU_VEL, dt);

        /* saturating response: slow cursor ≈ nothing, fast cursor tops out
           rather than tearing the word apart */
        var want = PULL_MAX * Math.tanh(vel * PULL_GAIN / PULL_MAX);
        /* gusting up is faster than settling down */
        var rising = Math.abs(want) > Math.abs(pull);
        pull = approach(pull, want, rising ? TAU_GUST : TAU_CALM, dt);
        if (Math.abs(pull) < 0.00012) pull = 0;
      }

      /* the smear is derived, not authored: whatever the word moved this
         frame — entrance push or cursor drag — is what blurs */
      breeze = approach(breeze, breezeTo, 0.9, dt);

      var shift = enter.offset + pull;
      var speed = (shift - prevShift) / Math.max(dt, 0.001);
      prevShift = shift;
      var wantSmear = Math.max(-SMEAR_MAX, Math.min(SMEAR_MAX, speed * TRAIL));
      smear = approach(smear, wantSmear, TAU_SMEAR, dt);
      if (Math.abs(smear) < 0.0002) smear = 0;

      draw();

      /* The breeze never settles, so there is no "at rest" to park on any
         more — the loop stops when the hero is scrolled away instead. */
      if (!onScreen && !gsap.isTweening(enter)) { running = false; return; }
      requestAnimationFrame(frame);
    }

    function wake() {
      if (running) return;
      running = true;
      last = 0;
      requestAnimationFrame(frame);
    }

    /* ─────────── entrance ─────────── */

    /* launch with the leading edge just past the left of the viewport, so the
       whole travel — and the distortion carried with it — happens on screen */
    var offset0 = -band.pivot - 0.02;
    enter.offset = offset0;
    enter.scale  = STRETCH;
    enter.alpha  = 0;

    var over = (band.textW / band.w) * 0.05;      /* overshoot, uv */

    var tl = gsap.timeline({
      onUpdate: wake,
      onComplete: function () {
        interactive = true;
        breezeTo = 1;
        disarm();
        wake();
      }
    });

    tl.fromTo(weEl, { opacity: 0, y: 30 },
      { opacity: 1, y: 0, duration: 0.80, ease: "power3.out" }, T_WE);

    tl.to(enter, { alpha: 1, duration: 0.14, ease: "none" }, T_AIR);

    /* momentum in, hard aerodynamic stop, then the overshoot is released —
       decelerating curves throughout, never an elastic bounce */
    tl.to(enter, { offset: over, duration: D_PUSH,   ease: "power3.out"   }, T_AIR)
      .to(enter, { offset: 0,    duration: D_SETTLE, ease: "power2.inOut" }, T_AIR + D_PUSH);

    /* drawn out while travelling, still wide as it lands, then the stop
       snaps it into compression before it relaxes to true proportions */
    tl.to(enter, { scale: ARRIVE,   duration: D_DRAW,   ease: "power2.out" }, T_AIR)
      .to(enter, { scale: COMPRESS, duration: D_SQUASH, ease: "power2.in"  }, T_AIR + D_DRAW)
      .to(enter, { scale: 1,        duration: D_RELAX,  ease: "power2.out" }, T_AIR + D_DRAW + D_SQUASH);

    addChrome(tl);
    guard(tl);
    wake();

    /* ─────────── cursor as a source of airflow ─────────── */

    window.addEventListener("pointermove", function (e) {
      if (!interactive || e.pointerType === "touch") return;
      var r = canvas.getBoundingClientRect();
      var nx = (e.clientX - r.left) / r.width;
      var ny = (e.clientY - r.top) / r.height;

      /* the field reaches beyond the band, but not across the whole page */
      if (ny < -1.4 || ny > 2.4) { target.y = ny; lastX = null; wake(); return; }

      if (lastX !== null) moved += nx - lastX;
      lastX = nx;
      target.x = nx;
      target.y = ny;
      wake();
    }, { passive: true });

    if (window.IntersectionObserver) {
      new IntersectionObserver(function (entries) {
        onScreen = entries[0].isIntersecting;
        if (onScreen) wake();
      }, { threshold: 0 }).observe(hero);
    }

    window.addEventListener("blur", function () { lastX = null; moved = 0; });
    document.addEventListener("visibilitychange", function () {
      lastX = null; moved = 0;
      if (!document.hidden) wake();
    });

    /* ─────────── resize / font swap / context loss ─────────── */

    var rebuild = (function () {
      var t;
      return function () {
        clearTimeout(t);
        /* Rebuild at any width. Once the shader path owns the headline it
           keeps it — bailing out on narrow viewports would leave a stale
           band pinned over a line box that has since moved. */
        t = setTimeout(function () { if (build()) wake(); }, 150);
      };
    })();

    window.addEventListener("resize", rebuild);
    if (document.fonts && document.fonts.addEventListener) {
      document.fonts.addEventListener("loadingdone", rebuild);
    }

    canvas.addEventListener("webglcontextlost", function (e) {
      e.preventDefault();
      running = false;
      interactive = false;
      airEl.style.opacity = "";     /* hand the headline back to the DOM */
      canvas.remove();
      disarm();
    });

    return true;
  }

  /* ═══════════════════ start ═══════════════════
     Wait for Gellix so the raster matches the page, but never let a slow
     font hold the hero hostage. */

  function start() {
    if (simple || !runShader()) runSimple();
  }

  var started = false;
  function once() { if (!started) { started = true; start(); } }

  if (document.fonts && document.fonts.ready) {
    document.fonts.load('600 100px "Gellix"').catch(function () {})
      .then(function () { return document.fonts.ready; })
      .then(once).catch(once);
    setTimeout(once, 1200);
  } else {
    once();
  }
})();
